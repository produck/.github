#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const PACKAGE_ROOT = path.resolve(SCRIPT_DIR, '..');
const REPO_ROOT = path.resolve(PACKAGE_ROOT, '../..');
const OUTPUT_PATH = path.resolve(PACKAGE_ROOT, 'publish-assets/instructions/org.instructions.md');
const SOURCE_FILES = [
  'docs/ai-collaboration.md',
  'docs/commit-convention.md',
  'docs/nodejs-initialization.md',
];

function normalize(text) {
  return text.replace(/\r\n/g, '\n').trimEnd() + '\n';
}

function stripTopTitle(markdown) {
  const lines = markdown.split('\n');
  if (lines.length > 0 && lines[0].startsWith('# ')) {
    return lines.slice(1).join('\n').replace(/^\n+/, '');
  }
  return markdown;
}

function loadSources() {
  return SOURCE_FILES.map((relativePath) => {
    const fullPath = path.resolve(REPO_ROOT, relativePath);
    if (!fs.existsSync(fullPath)) {
      throw new Error(`Missing source file: ${relativePath}`);
    }
    const text = normalize(fs.readFileSync(fullPath, 'utf8'));
    return {
      relativePath,
      content: stripTopTitle(text).trimEnd(),
    };
  });
}

function buildContent() {
  const header = [
    '# Organization Collaboration Instructions',
    '',
    'This file is generated at package publish time from organization docs.',
    'Do not edit this file directly.',
    '',
  ].join('\n');

  const sections = loadSources().map((entry) => {
    return [`## Source: ${entry.relativePath}`, '', entry.content, ''].join('\n');
  });

  return normalize(header + sections.join('\n'));
}

function run() {
  const content = buildContent();
  fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
  fs.writeFileSync(OUTPUT_PATH, content, 'utf8');
  process.stdout.write(`Generated ${OUTPUT_PATH}\n`);
}

run();
